// Turns the Shadertoy `Image` pass in `native/shader-src/Image.txt` into the
// HLSL the app compiles at startup.
//
// naga's GLSL front end cannot parse sampler or texture declarations at all
// (`front/glsl/parser/types.rs` knows no opaque types), so the conversion is
// spelled out here instead: every difference between the two languages this
// shader actually uses is handled once, in a place a reader can check.
//
//   cargo run --manifest-path native/tools/convert-shader/Cargo.toml
//
// The rules, and why each one is there:
//
//   * `vecN`/`ivecN`/`bvecN` are `floatN`/`intN`/`boolN`.
//   * GLSL matrices are column-major. `mat2(a,b,c,d)` builds the columns (a,b)
//     and (c,d); HLSL's `float2x2(a,b,c,d)` builds the rows. `glsl_mat2` /
//     `glsl_mat3` take GLSL's arguments and return the same matrix, so the one
//     place a transpose could sneak in is the helper, not 23 call sites.
//   * `m * v` in GLSL is a matrix times a column vector; HLSL spells that
//     `mul(m, v)`. `v * m` is a row vector times a matrix: `mul(v, m)`. There
//     are twelve such products; they are listed by hand below, because no regex
//     knows which side of a `*` is a matrix.
//   * `mod` is floor-based in GLSL and truncates in HLSL, hence `glsl_mod`.
//   * `texture`/`textureLod` take the sampler inline; HLSL needs a texture and a
//     sampler apart, so `texture(iChannel0, uv, bias)` becomes `tex0(uv, bias)`
//     and the overloads pick `Sample` or `SampleBias`.
//   * Shadertoy's `iResolution`, `iTime`, `iMouse` and `iChannelResolution` come
//     from a constant buffer.

use std::io::Write as _;
use std::path::PathBuf;

use regex::Regex;

/// Declarations every generated shader starts with: the Shadertoy uniforms, the
/// three channels, the helpers the rules above need.
const PRELUDE: &str = r#"// Generated by tools/convert-shader from shader-src/Image.txt. Do not edit.

cbuffer Globals : register(b0)
{
    float3 iResolution;
    float iTime;
    float4 iMouse;
    float3 iChannelResolution[4];
};

// Shadertoy lets helpers read the fragment coordinate; this carries it in.
static float2 gl_FragCoord;

Texture2D Channel0 : register(t0);
Texture2D Channel1 : register(t1);
Texture2D Channel2 : register(t2);
SamplerState Sample0 : register(s0);
SamplerState Sample1 : register(s1);
SamplerState Sample2 : register(s2);

float4 tex0(float2 uv) { return Channel0.Sample(Sample0, uv); }
// Shadertoy writes `texture(ch, uv, -100.)` to mean "the sharpest level"; GLSL
// clamps that to level 0, so the bias forms pin the level instead of biasing,
// which D3D would otherwise fold into a derivative the driver is free to
// reinterpret at extreme values.
float4 tex0(float2 uv, float bias) { return Channel0.SampleLevel(Sample0, uv, max(bias, 0.0)); }
float4 texlod0(float2 uv, float lod) { return Channel0.SampleLevel(Sample0, uv, max(lod, 0.0)); }
float4 tex1(float2 uv) { return Channel1.Sample(Sample1, uv); }
float4 tex1(float2 uv, float bias) { return Channel1.SampleLevel(Sample1, uv, max(bias, 0.0)); }
float4 texlod1(float2 uv, float lod) { return Channel1.SampleLevel(Sample1, uv, max(lod, 0.0)); }
float4 tex2(float2 uv) { return Channel2.Sample(Sample2, uv); }
float4 tex2(float2 uv, float bias) { return Channel2.SampleLevel(Sample2, uv, max(bias, 0.0)); }
float4 texlod2(float2 uv, float lod) { return Channel2.SampleLevel(Sample2, uv, max(lod, 0.0)); }

float  glsl_mod(float x, float y)  { return x - y * floor(x / y); }
float2 glsl_mod(float2 x, float y) { return x - y * floor(x / y); }
float3 glsl_mod(float3 x, float y) { return x - y * floor(x / y); }
float4 glsl_mod(float4 x, float y) { return x - y * floor(x / y); }
float2 glsl_mod(float2 x, float2 y) { return x - y * floor(x / y); }
float3 glsl_mod(float3 x, float3 y) { return x - y * floor(x / y); }

// A macro, not a function: HLSL only accepts constant expressions as global
// initialisers, and a function call is not one.
#define glsl_mat2(a, b, c, d) float2x2((a), (c), (b), (d))

float3x3 glsl_mat3(float3 c0, float3 c1, float3 c2)
{
    return float3x3(c0.x, c1.x, c2.x, c0.y, c1.y, c2.y, c0.z, c1.z, c2.z);
}
float3x3 glsl_mat3(float a, float b, float c, float d, float e, float f, float g, float h, float i)
{
    return float3x3(a, d, g, b, e, h, c, f, i);
}

"#;

const EPILOGUE: &str = r#"
struct VSOut
{
    float4 position : SV_Position;
};

float4 PSMain(VSOut input) : SV_Target
{
    // Shadertoy's gl_FragCoord starts at the bottom left; Direct3D's SV_Position
    // starts at the top left, so the y the shader sees is flipped back.
    float2 fragCoord = float2(input.position.x, iResolution.y - input.position.y);
    gl_FragCoord = fragCoord;
    float4 color = float4(0.0, 0.0, 0.0, 1.0);
    mainImage(color, fragCoord);
    return color;
}
"#;

/// The twelve matrix products in the shader, by hand: `(from, to)`.
///
/// `v * m` and `m * v` are not textually separable, so each site is written out
/// and the converter refuses to run when one of them goes missing.
const MATRIX_PRODUCTS: &[(&str, &str)] = &[
    (
        "raydirection *= rotY;",
        "raydirection = mul(raydirection, rotY);",
    ),
    (
        "dir = normalize(dir) * rotX * rotY * rotZ;",
        "dir = mul(mul(mul(normalize(dir), rotX), rotY), rotZ);",
    ),
    (
        "vec3 camera_vector = get_camera_vector(iResolution, fragCoord, Dfact)* rotZ * rotY * rotX;",
        "vec3 camera_vector = mul(mul(mul(get_camera_vector(iResolution, fragCoord, Dfact), rotZ), rotY), rotX);",
    ),
    (
        "uv = uv * mat2(end.x, end.y, -end.y, end.x);",
        "uv = mul(uv, glsl_mat2(end.x, end.y, -end.y, end.x));",
    ),
    ("p *= mm2(p.x*0.06);", "p = mul(p, mm2(p.x*0.06));"),
    ("dg *= mm2(t*spd);", "dg = mul(dg, mm2(t*spd));"),
    ("p*= -m2;", "p = mul(p, -m2);"),
    (
        "uv *= sea_octave_m; freq *= 1.9; amp *= 0.22;",
        "uv = mul(uv, sea_octave_m); freq *= 1.9; amp *= 0.22;",
    ),
    (
        "star = stars(vec3(camera_vector.xy*ma2,camera_vector.z -camz));",
        "star = stars(vec3(mul(camera_vector.xy, ma2), camera_vector.z - camz));",
    ),
    ("D1.xy *=ma2;", "D1.xy = mul(D1.xy, ma2);"),
    ("b.xy *=ma2;", "b.xy = mul(b.xy, ma2);"),
    ("Dn.xy *=ma2;", "Dn.xy = mul(Dn.xy, ma2);"),
];

/// GLSL the mechanical rules cannot reach: `cond ? a = x : a = y` is a
/// conditional expression with assignments for arms, which HLSL rejects.
const MANUAL_FIXES: &[(&str, &str)] = &[
    // The export ships with the simplified sky, which skips the whole
    // atmosphere and the volumetric cloud layer; the full pass is what the
    // published shader shows.


    (
    "q.y > (0.2 * (moon_size/2.0)/M) ? thing = 1.0:  thing = (q.y / ((moon_size/2.0)/M))*5.0;",
    "if (q.y > (0.2 * (moon_size/2.0)/M)) { thing = 1.0; } else { thing = (q.y / ((moon_size/2.0)/M))*5.0; }",
)];
/// GLSL spellings that differ from HLSL, applied in this order.
fn rewrite(source: &str) -> String {
    let mut text = source.to_string();

    for (from, to) in MATRIX_PRODUCTS {
        if !text.contains(from) {
            eprintln!("matrix product moved, update MATRIX_PRODUCTS: {from}");
            std::process::exit(1);
        }
        text = text.replace(from, to);
    }

// `textureLod` before `texture`.
    for (call, helper) in [("textureLod", "texlod"), ("texture", "tex")] {
        for channel in 0..3 {
            let pattern = format!(r"{call}\s*\(\s*iChannel{channel}\s*,");
            let replacement = format!("{helper}{channel}(");
            text = Regex::new(&pattern)
                .unwrap()
                .replace_all(&text, replacement.as_str())
                .into_owned();
        }
    }

    // Matrix constructors before the matrix types.
    // A boundary so the `glsl_mat2(` the matrix-product table already wrote is
    // not matched again.
    for (from, to) in [("mat2", "glsl_mat2"), ("mat3", "glsl_mat3")] {
        let pattern = format!(r"(^|[^A-Za-z0-9_]){from}\s*\(");
        let replacement = format!("${{1}}{to}(");
        text = Regex::new(&pattern)
            .unwrap()
            .replace_all(&text, replacement.as_str())
            .into_owned();
    }

    let rules: &[(&str, &str)] = &[
        (r"\bvec([234])\b", "float$1"),
        (r"\bivec([234])\b", "int$1"),
        (r"\bbvec([234])\b", "bool$1"),
        (r"\bmat2\b", "float2x2"),
        (r"\bmat3\b", "float3x3"),
        (r"\bfract\b", "frac"),
        (r"\binversesqrt\b", "rsqrt"),
        (r"\bmod\s*\(", "glsl_mod("),
        // GLSL's mix is HLSL's lerp; saturate already is HLSL's.
        (r"\bmix\s*\(", "lerp("),
        (r"\btexture2D\s*\(", "tex0("),
    ];
    for (pattern, replacement) in rules {
        text = Regex::new(pattern)
            .unwrap()
            .replace_all(&text, *replacement)
            .into_owned();
    }

    // This HLSL compiler rejects the scalar splat written as a constructor
    // (`float3(0.5)`, `float3(f(x))`); the cast spells the same thing and is
    // accepted. Arguments are found by matching parentheses, not with a regex.
    text = fix_scalar_splats(&text);
    // HLSL reads a global `const` with an initializer as an external constant
    // the app must supply; `static const` is the literal GLSL means.
    text = Regex::new(r"(?m)^const\s+")
        .unwrap()
        .replace_all(&text, "static const ")
        .into_owned();
    // GLSL's two-argument `atan(y, x)` is HLSL's `atan2`.
    text = text.replace("atan(main.x,main.y)", "atan2(main.x, main.y)");

    // A global `float x = ...` is not a GLSL global. FXC puts it in the
    // implicit `$Globals` buffer, the app never binds that buffer, and the
    // value reads back as 0. `cloudfar` being 0 makes the cloud distance
    // factor clamp to 0, which erases the layer. `static` keeps the
    // initializer and stays inside the invocation, which is what GLSL does.
    text = static_globals(&text);

    // Float literals: GLSL writes `.5` and `2.`, HLSL wants a digit on both
    // sides of the point.
    // `regex` has no look-around, so both rules capture the neighbouring
    // character and put it back.
    // A number starts at a boundary: `col2.rgb` is a member access, not `col2.0`.
    text = Regex::new(r"(^|[^0-9A-Za-z_.])\.([0-9])")
        .unwrap()
        .replace_all(&text, "${1}0.$2")
        .into_owned();
    text = Regex::new(r"(^|[^0-9A-Za-z_.])([0-9])\.([^0-9])")
        .unwrap()
        .replace_all(&text, "${1}${2}.0${3}")
        .into_owned();
    text = Regex::new(r"(?m)(^|[^0-9A-Za-z_.])([0-9])\.$")
        .unwrap()
        .replace_all(&text, "${1}${2}.0")
        .into_owned();

    

    for (from, to) in MANUAL_FIXES {
        if !text.contains(from) {
            eprintln!("manual fix no longer applies, update MANUAL_FIXES: {from}");
            std::process::exit(1);
        }
        text = text.replace(from, to);
    }

    text
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .canonicalize()
        .expect("native/");
    let source_path = root.join("shader-src").join("Image.txt");
    let output_path = root.join("src").join("ocean.hlsl");

    let body = std::fs::read_to_string(&source_path).expect("Image.txt");
    // The export uses CRLF line endings; every rule below matches on "\n".
    let body = body.replace("\r\n", "\n");
    let body = rewrite(&body);

    let mut file = String::with_capacity(PRELUDE.len() + body.len() + EPILOGUE.len());
    file.push_str(PRELUDE);
    file.push_str(&body);
    file.push_str(EPILOGUE);

    std::fs::write(&output_path, file).expect("write ocean.hlsl");
    let lines = std::fs::read_to_string(&output_path)
        .map(|text| text.lines().count())
        .unwrap_or(0);
    let mut out = std::io::stdout();
    let _ = writeln!(out, "wrote {} ({lines} lines)", output_path.display());
}

/// File-scope variables the GLSL initializes and then only reads. Matched by
/// name, at column 0, because this shader also leaves some function locals
/// unindented.
const GLOBAL_NAMES: &[&str] = &[
    "bM2",
    "bR",
    "Ds",
    "Dsm",
    "cloudyhigh",
    "cloudnear",
    "cloudfar",
    "m2",
    "SIZE_RATE",
    "XSPEED",
    "YSPEED",
    "LAYERS",
];

fn static_globals(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 64);
    for line in text.split_inclusive('\n') {
        let body = line.trim_end_matches(['\n', '\r']);
        let is_global = !body.starts_with("//")
            && !body.starts_with("static ")
            && GLOBAL_NAMES.iter().any(|name| {
                let Some((_, after_type)) = body.split_once(char::is_whitespace) else {
                    return false;
                };
                let after_type = after_type.trim_start();
                after_type.strip_prefix(name).is_some_and(|rest| rest.trim_start().starts_with('='))
            });
        if is_global {
            out.push_str("static ");
        }
        out.push_str(line);
    }
    out
}

fn is_ident(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_'
}

/// Rewrites `floatN(x)` with one argument to `(floatN)(x)`.
fn fix_scalar_splats(text: &str) -> String {
    let bytes = text.as_bytes();
    let mut out = String::with_capacity(text.len());
    let mut i = 0usize;
    while i < text.len() {
        let mut found = None;
        for n in [2usize, 3, 4] {
            let head = format!("float{n}(");
            if text[i..].starts_with(&head) && (i == 0 || !is_ident(bytes[i - 1])) {
                found = Some((n, head.len()));
                break;
            }
        }
        let Some((n, head_len)) = found else {
            let ch = text[i..].chars().next().unwrap();
            out.push(ch);
            i += ch.len_utf8();
            continue;
        };
        let open = i + head_len - 1;
        let mut depth = 0i32;
        let mut comma = false;
        let mut close = None;
        for (k, ch) in text[open..].char_indices() {
            match ch {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        close = Some(open + k);
                        break;
                    }
                }
                ',' if depth == 1 => comma = true,
                _ => {}
            }
        }
        match close {
            Some(close) if !comma => {
                out.push_str(&format!("(float{n})("));
                out.push_str(&text[open + 1..close]);
                out.push(')');
                i = close + 1;
            }
            _ => {
                out.push_str(&text[i..open + 1]);
                i = open + 1;
            }
        }
    }
    out
}